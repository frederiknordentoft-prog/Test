/**
 * Føllenes hale er større (review G1-r4: den mindste araber og shetlandspony læstes som en kat i silhuet), så den
 * står tydeligt frem ved siden af den lille krop. Halen skaleres om sin rod (tailBase).
 */
const FOAL_TAIL = 1.35
/**
 * Halen pr. stadie: føllet får en større hale, og araberens løftede hale vokser lidt mindre på stor (`big`), så
 * spidsen ikke når hoften og lukker en løkke af baggrund under buen (review G1-r4).
 */
const stagedTail = (part: Part, big = 1): Part => (p) => {
  const k = p.stage === 1 ? FOAL_TAIL : p.stage === 3 ? big : 1
  return k === 1 ? part(p) : <g transform={`scale(${k})`}>{part({ ...p, sw: p.sw / k })}</g>
}

